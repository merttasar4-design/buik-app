#!/usr/bin/env python3
"""Kulüp Stüdyosu'ndan indirilen brand.json'ı uygulamaya işler.

Kullanım (proje kökünden):
    python3 tool/brand/apply_brand.py ~/Downloads/odtu-kulup.brand.json
    python3 tool/brand/apply_brand.py tool/brand/buik.brand.json   # BUİK'e geri dön

Yaptıkları:
  - lib/config/brand.dart'ı yeniden üretir (isim, slogan, renkler)
  - assets/brand/logo.png ve assets/brand/app_icon.png'yi yazar
  - iOS/Android'de ana ekranda görünen uygulama adını günceller
  - flutter_launcher_icons ile ikon setlerini yeniden üretir (--no-icons ile atlanır)
  - --bundle-id verilirse iOS/Android paket kimliğini de değiştirir
"""
import argparse
import base64
import io
import json
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
HEX = re.compile(r"^#[0-9A-Fa-f]{6}$")


def dart_str(value: str) -> str:
    escaped = (
        value.replace("\\", "\\\\")
        .replace("'", "\\'")
        .replace("$", "\\$")
        .replace("\n", "\\n")
    )
    return f"'{escaped}'"


def dart_color(hex_value: str) -> str:
    if not HEX.match(hex_value):
        sys.exit(f"Geçersiz renk: {hex_value} (#RRGGBB bekleniyor)")
    return f"Color(0xFF{hex_value[1:].upper()})"


def decode_data_url(data_url: str) -> bytes:
    if not data_url.startswith("data:image/png;base64,"):
        sys.exit("Logo/ikon PNG data URL olmalı (Stüdyo'dan alınan dosyayı kullan).")
    return base64.b64decode(data_url.split(",", 1)[1])


def write_png(path: pathlib.Path, data: bytes, opaque: bool) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if opaque:
        # App Store alfa kanallı ikonu reddediyor; Pillow varsa garantiye al.
        try:
            from PIL import Image

            img = Image.open(io.BytesIO(data)).convert("RGBA")
            bg = Image.new("RGB", img.size, (255, 255, 255))
            bg.paste(img, mask=img.split()[3])
            buf = io.BytesIO()
            bg.save(buf, "PNG")
            data = buf.getvalue()
        except ImportError:
            pass
    path.write_bytes(data)


def render_brand_dart(cfg: dict) -> str:
    c = cfg["colors"]
    full_name = cfg["fullName"].replace("\\n", "\n")
    return f"""// GENERATED by tool/brand/apply_brand.py — elle düzenleme; kulüp markası
// değiştirilecekse Kulüp Stüdyosu'ndan brand.json alıp script'i çalıştır.
import 'package:flutter/material.dart';

/// Uygulamanın kulübe özel kimliği. Tüm ekranlar ismi, logoyu ve marka
/// rengini buradan okur; bu sayede aynı kod başka kulüplere uyarlanabiliyor.
class Brand {{
  Brand._();

  /// Kısa ad — giriş ekranı, menü başlığı, uygulama başlığı.
  static const String shortName = {dart_str(cfg["shortName"])};

  /// Açılış ekranında logonun altında görünen tam ad (satır sonu `\\n`).
  static const String fullName =
      {dart_str(full_name)};

  /// Açılış ekranındaki slogan; boşsa gösterilmez.
  static const String slogan = {dart_str(cfg.get("slogan", ""))};

  /// Kulübün bağlı olduğu üniversitenin kısa adı (ör. "Boğaziçi").
  static const String university = {dart_str(cfg.get("university", ""))};

  static const String logoAsset = 'assets/brand/logo.png';

  static const Color primary = {dart_color(c["primary"])};
  static const Color primaryLight = {dart_color(c["primaryLight"])};

  static const Color lightBrandSoft = {dart_color(c["lightBrandSoft"])};
  static const Color darkBrandSoft = {dart_color(c["darkBrandSoft"])};
}}
"""


def replace_in(path: pathlib.Path, pattern: str, repl: str, label: str) -> None:
    text = path.read_text()
    new, n = re.subn(pattern, repl, text)
    if n == 0:
        print(f"  ! {label}: eşleşme bulunamadı ({path.relative_to(ROOT)})")
        return
    path.write_text(new)
    print(f"  ✓ {label}")


def xml_escape(value: str) -> str:
    return (
        value.replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("config", type=pathlib.Path)
    parser.add_argument("--no-icons", action="store_true", help="ikon setlerini üretme")
    parser.add_argument(
        "--bundle-id",
        action="store_true",
        help="brand.json'daki bundleId'yi iOS/Android paket kimliğine uygula",
    )
    args = parser.parse_args()

    cfg = json.loads(args.config.expanduser().read_text())
    for key in ("shortName", "fullName", "colors", "logo", "appIcon"):
        if key not in cfg:
            sys.exit(f"brand.json içinde '{key}' eksik.")

    print(f"→ {cfg['shortName']} markası uygulanıyor")

    (ROOT / "lib/config/brand.dart").write_text(render_brand_dart(cfg))
    print("  ✓ lib/config/brand.dart")

    write_png(ROOT / "assets/brand/logo.png", decode_data_url(cfg["logo"]), opaque=False)
    write_png(ROOT / "assets/brand/app_icon.png", decode_data_url(cfg["appIcon"]), opaque=True)
    print("  ✓ assets/brand/logo.png, app_icon.png")

    display = xml_escape(cfg["shortName"])
    replace_in(
        ROOT / "ios/Runner/Info.plist",
        r"(<key>CFBundleDisplayName</key>\s*<string>)[^<]*(</string>)",
        rf"\g<1>{display}\g<2>",
        "iOS ana ekran adı",
    )
    replace_in(
        ROOT / "android/app/src/main/AndroidManifest.xml",
        r'android:label="[^"]*"',
        f'android:label="{display}"',
        "Android ana ekran adı",
    )

    if args.bundle_id:
        bundle_id = cfg.get("bundleId", "")
        if not re.match(r"^[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*)+$", bundle_id):
            sys.exit(f"Geçersiz bundleId: '{bundle_id}'")
        gradle = next((ROOT / "android/app").glob("build.gradle*"))
        replace_in(gradle, r'applicationId = "[^"]*"', f'applicationId = "{bundle_id}"', "Android applicationId")
        replace_in(
            ROOT / "ios/Runner.xcodeproj/project.pbxproj",
            r"PRODUCT_BUNDLE_IDENTIFIER = [^;]*?(\.RunnerTests)?;",
            lambda m: f"PRODUCT_BUNDLE_IDENTIFIER = {bundle_id}{m.group(1) or ''};",
            "iOS bundle identifier",
        )
        print(
            "  ! Yeni paket kimliği için Firebase'de yeni iOS/Android uygulaması açıp\n"
            "    GoogleService-Info.plist ve google-services.json dosyalarını değiştirmeyi unutma."
        )

    if not args.no_icons:
        print("  … uygulama ikonları üretiliyor")
        subprocess.run(["dart", "run", "flutter_launcher_icons"], cwd=ROOT, check=True)

    print("Bitti. `flutter run` ile kontrol edebilirsin.")


if __name__ == "__main__":
    main()
